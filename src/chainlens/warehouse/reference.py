def industry_name(code: str | None) -> str:
    """行业代码 -> 中文名称。未收录时逐级回退，绝不编造。"""
    if not code:
        return "未标注行业"
    code = str(code).strip().upper()
    if code in INDUSTRY_CLASSES:
        return INDUSTRY_CLASSES[code]
    division = code[:3]
    if division in INDUSTRY_DIVISIONS:
        return f"{INDUSTRY_DIVISIONS[division]}（细类未映射）"
    section = code[:1]
    if section in INDUSTRY_SECTIONS:
        return f"{INDUSTRY_SECTIONS[section]}（细类未映射）"
    return f"未知行业 {code}"


def industry_section_name(code: str | None) -> str:
    if not code:
        return "未标注"
    return INDUSTRY_SECTIONS.get(str(code)[:1].upper(), "未知门类")


