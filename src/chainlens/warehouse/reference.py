def district_name(code: str | None) -> str:
    """区划代码 -> 名称。市本级（xx00）自动识别，未知代码原样返回并标注。"""
    if not code:
        return "未标注区划"
    code = str(code).strip()
    if code in DISTRICT_NAMES:
        return DISTRICT_NAMES[code]
    if len(code) == 6 and code.endswith("00") and code[:4] in CITY_NAMES:
        return f"{CITY_NAMES[code[:4]]}（市本级）"
    if len(code) == 6 and code[:4] in CITY_NAMES:
        return f"{CITY_NAMES[code[:4]]}（区划未映射 {code}）"
    return f"未知区划 {code}"


def city_name(code: str | None) -> str:
    if not code:
        return "未标注"
    code = str(code).strip()
    return CITY_NAMES.get(code[:4], district_name(code))


